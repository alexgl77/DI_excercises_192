        "        self.scale = 1.0 / math.sqrt(hidden_dim)",
        "        self.W_q = nn.Linear(hidden_dim, hidden_dim, bias=False)",
        "        self.W_k = nn.Linear(hidden_dim, hidden_dim, bias=False)",
